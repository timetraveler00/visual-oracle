"""EXP04 FourPeople freeze source and preview integrity verifier.

Run in the EXP04 project folder:
    python exp04_verify_fourpeople.py

Checks Y4M pixels outside the frame-number barcode region (top 128 pixels):
  - inactive fault frames must equal FourPeople source frames;
  - freeze frames 150..349 must equal source frame 150;
  - FourPeople source must differ from the historical Shields source;
  - the generated PNG preview must match freeze Y4M frame 150.
This does not calculate 640x360 SSIM or validate WebRTC receiver captures.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

import cv2
import numpy as np


class Y4M:
    def __init__(self, path: Path):
        self.path = path
        self.offsets = []
        with path.open('rb') as fh:
            header = fh.readline().decode('ascii', errors='replace').strip()
            if not header.startswith('YUV4MPEG2 '):
                raise ValueError(f'Not a Y4M file: {path}')
            tokens = header.split()[1:]
            props = {t[0]: t[1:] for t in tokens if len(t) >= 2}
            self.width, self.height = int(props['W']), int(props['H'])
            chroma = props.get('C', '420')
            if not chroma.startswith('420'):
                raise ValueError(f'Only 8-bit 4:2:0 Y4M supported, found {chroma}')
            self.frame_bytes = self.width * self.height * 3 // 2
            while True:
                marker = fh.readline()
                if not marker:
                    break
                if not marker.startswith(b'FRAME'):
                    raise ValueError(f'Invalid frame marker at frame {len(self.offsets)} in {path}')
                self.offsets.append(fh.tell())
                fh.seek(self.frame_bytes, 1)
                if fh.tell() > path.stat().st_size:
                    raise ValueError(f'Truncated frame in {path}')
            if fh.tell() != path.stat().st_size:
                raise ValueError(f'Unexpected file tail in {path}')

    def frame(self, n: int) -> np.ndarray:
        with self.path.open('rb') as fh:
            fh.seek(self.offsets[n])
            data = fh.read(self.frame_bytes)
        if len(data) != self.frame_bytes:
            raise ValueError(f'Frame {n} incomplete: {self.path}')
        return np.frombuffer(data, dtype=np.uint8).reshape(self.height * 3 // 2, self.width)

    def y_region(self, n: int) -> np.ndarray:
        # The overlay generated by 07_create_numbered_y4m.py is y=12..127.
        # For real 720p clips, compare the unmodified region y=128..719.
        top = 128 if self.height > 256 else 0
        return self.frame(n)[top:self.height, :]


def mae(a: np.ndarray, b: np.ndarray) -> float:
    return float(np.mean(np.abs(a.astype(np.int16) - b.astype(np.int16))))


def run(root: Path, fault_arg: str | None):
    source_path = root / 'videos' / '720p50_fourpeople_exp04.y4m'
    shields_path = root / 'videos' / '720p50_shields_ter.y4m'
    matches = sorted((root / 'fault_sources').glob(
        '720p50_fourpeople_exp04_*/720p50_shields_ter_fault_freeze_medium.y4m'))
    if fault_arg:
        fault_path = Path(fault_arg).resolve()
    elif len(matches) == 1:
        fault_path = matches[0]
    else:
        raise ValueError(f'Expected one freeze file; found {len(matches)}. Specify --fault <path>.')

    for p in (source_path, shields_path, fault_path):
        if not p.is_file():
            raise FileNotFoundError(p)
    source, shields, fault = Y4M(source_path), Y4M(shields_path), Y4M(fault_path)
    print('Source:', source_path)
    print('Freeze:', fault_path)
    print('FourPeople:', source.width, 'x', source.height, '| frames:', len(source.offsets))
    print('Freeze:', fault.width, 'x', fault.height, '| frames:', len(fault.offsets))
    if (source.width, source.height, len(source.offsets)) != (fault.width, fault.height, len(fault.offsets)):
        raise ValueError('Source/fault geometry or frame count mismatch')
    if len(source.offsets) < 401 or len(shields.offsets) < 401:
        raise ValueError('Not enough frames for validation')

    meta_path = fault_path.with_suffix('.json')
    if meta_path.is_file():
        metadata = json.loads(meta_path.read_text(encoding='utf-8-sig'))
        print('Fault metadata reference:', metadata.get('reference_video'))
        if metadata.get('reference_video') != source_path.name:
            raise ValueError('Fault metadata points to a different source video')
        if (metadata.get('fault_start_frame'), metadata.get('fault_end_frame')) != (150, 349):
            raise ValueError('Unexpected freeze interval in fault metadata')
    else:
        print('WARNING: Fault metadata JSON missing')

    checks = []
    for n in (100, 149, 350, 400):
        d = mae(source.y_region(n), fault.y_region(n))
        ok = d == 0.0
        print(f'Inactive frame {n:03d}: source-vs-fault MAE={d:.6f} -> {"PASS" if ok else "FAIL"}')
        checks.append(ok)

    anchor = source.y_region(150)
    for n in (150, 200, 300, 349):
        d = mae(anchor, fault.y_region(n))
        ok = d == 0.0
        print(f'Freeze frame   {n:03d}: anchor-vs-fault MAE={d:.6f} -> {"PASS" if ok else "FAIL"}')
        checks.append(ok)

    for n in (100, 400):
        d = mae(source.y_region(n), shields.y_region(n))
        ok = d > 1.0
        print(f'Video identity {n:03d}: FourPeople-vs-Shields MAE={d:.3f} -> {"PASS" if ok else "CHECK"}')
        checks.append(ok)

    preview_path = fault_path.with_name(fault_path.stem + '_preview.png')
    if preview_path.is_file():
        preview = cv2.imread(str(preview_path), cv2.IMREAD_COLOR)
        expected = cv2.cvtColor(fault.frame(150), cv2.COLOR_YUV2BGR_I420)
        if preview is None or preview.shape != expected.shape:
            raise ValueError('Preview cannot be decoded or dimensions differ')
        d = mae(preview, expected)
        ok = d == 0.0
        print(f'Preview PNG matches freeze frame 150: MAE={d:.6f} -> {"PASS" if ok else "FAIL"}')
        checks.append(ok)
    else:
        print('WARNING: Preview PNG not found; preview comparison skipped')
        checks.append(False)

    if all(checks):
        print('\nVERIFIED: FourPeople source, freeze behavior, and preview content are consistent.')
        return 0
    print('\nNOT VERIFIED: At least one check failed; do not proceed with the main experiment.')
    return 1


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parent)
    parser.add_argument('--fault', default=None)
    args = parser.parse_args()
    try:
        sys.exit(run(args.root.resolve(), args.fault))
    except Exception as exc:
        print('ERROR:', exc, file=sys.stderr)
        sys.exit(2)
